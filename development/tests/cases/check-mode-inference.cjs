const assert=require('node:assert/strict');
require('../../src/scripts/validation/logic-engine.js');
require('../../src/scripts/validation/categorical-logic.js');
require('../../src/scripts/validation/first-order-syntax.js');
const {inspect}=require('../../src/scripts/validation/logic-mode-inference.js');
const rows=(...formulas)=>formulas.map((text,i)=>({text,role:i===formulas.length-1?'conclusion':'premise'}));
const prop=rows('A → B','A','B'), fol=rows('∀x(P(x) → Q(x))','P(a)','Q(a)'),cat=rows('A(M,P)','A(S,M)','A(S,P)');
for(const [mode,data] of [['propositional',prop],['first-order',fol],['syllogistic',cat]])assert.equal(inspect(data,mode),null);
for(const selected of ['propositional','syllogistic'])assert.equal(inspect(fol,selected).suggested,'first-order');
for(const selected of ['propositional','first-order'])assert.equal(inspect(cat,selected).suggested,'syllogistic');
assert.equal(inspect(prop,'syllogistic').suggested,'propositional');
assert.equal(inspect(prop,'first-order'),null,'propositional formulas are also accepted in FOL');
assert.equal(inspect(rows('Todo cão é animal','Todo animal é cão'),'propositional').suggested,'syllogistic');
assert.equal(inspect(rows('P(a)','P(a,b)'),'propositional').suggested,'first-order','signature problems do not change grammatical classification');
for(const data of [[],rows('A →'),rows('∀x(P(x)'),rows('□P'),rows('A(M,P)','P(a)'),rows('A(s,p)')])assert.equal(inspect(data,'propositional'),null,'no confident classification for incomplete, unsupported, mixed or ambiguous notation');
assert.equal(inspect(rows('x = y'),'propositional').suggested,'first-order');
assert.equal(inspect(rows('P(a)'),'propositional').suggested,'first-order');
assert.equal(inspect([...prop,{text:'∀',role:'blank'}],'propositional'),null,'blank roles ignored');
assert.equal(inspect(Array.from({length:201},()=>({text:'A',role:'premise'})),'propositional'),null);
const before=JSON.stringify(fol);inspect(fol,'propositional');assert.equal(JSON.stringify(fol),before);
console.log('Mode inference: supported grammars, overlaps, ambiguity, malformed/unsupported/mixed input, limits and immutability passed.');
