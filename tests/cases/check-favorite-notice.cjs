const fs = require("fs"), assert = require("assert/strict");
const { chromium } = require("../browser-runtime.cjs");
(async () => {
  const browser = await chromium.launch({  headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.route("https://lp.test/**", r => r.fulfill({ contentType: "text/html", body: fs.readFileSync("index.html", "utf8") }));
    await page.goto("https://lp.test");
    await page.evaluate(() => favoriteNotice("Removed from favorites"));
    const notice = page.locator(".hy-favorite-notice");
    await notice.hover();
    await page.waitForTimeout(1400);
    assert(await notice.isVisible(), "hover keeps notification open");
    assert.equal(await notice.textContent(), "Removed from favorites");
    const box = await notice.boundingBox();
    assert(Math.abs(box.x + box.width / 2 - 195) < 1);
    assert(box.y + box.height <= 823);
    await page.screenshot({ path: "test-artifacts/favorite-notice-mobile.png" });
    await page.mouse.move(0, 0);
    await page.waitForTimeout(700);
    assert(await notice.isVisible(), "leave restarts full second");
    await page.waitForTimeout(350);
    const frames = await notice.evaluate(e => e.getAnimations()[0]?.effect.getKeyframes());
    assert(frames?.at(-1).transform.includes("14px"), "exit moves downward");
    await notice.waitFor({ state: "hidden" });
    await page.evaluate(() => favoriteNotice("Added to favorites"));
    await page.waitForTimeout(800);
    await page.evaluate(() => favoriteNotice("Removed from favorites"));
    await page.waitForTimeout(700);
    assert(await notice.isVisible(), "new notification replaces old timeout");
    await notice.waitFor({ state: "hidden" });
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.evaluate(() => favoriteNotice("Removed from favorites"));
    assert(await notice.isVisible());
    await notice.waitFor({ state: "hidden" });
    assert.deepEqual(errors, []);
    console.log("Favorite notice: bottom position, hover pause, full restart, replacement, downward exit and reduced motion OK");
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
